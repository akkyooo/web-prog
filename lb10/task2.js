var dayOfWeek = "понеділок";
switch (dayOfWeek) 
{
    case "понеділок":
        console.log("Це перший день тижня");
        break;
    case "вівторок":
        console.log("Це другий день тижня");
        break;
    case "середа":
        console.log("Це третій день тижня");
        break;
    case "четвер":
        console.log("Це четвертий день тижня");
        break;
    case "п'ятниця":
        console.log("Це п'ятий день тижня");
        break;
    case "субота":
        console.log("Це шостий день тижня");
        break;
    case "неділя":
        console.log("Це сьомий день тижня");
        break;
    default:
        console.log("Невідомий день тижня");
}